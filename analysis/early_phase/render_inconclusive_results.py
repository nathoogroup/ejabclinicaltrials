#!/usr/bin/env python3
"""Render reviewed results for transfer into the consolidated response."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
rows = list(csv.DictReader((ROOT / "analysis/early_phase/outputs/inconclusive_posterior_summary.csv").open()))
pooled = [r for r in rows if r["significance_rule"] == "p_two_sided" and r["group"] == "All"]
selected, = [r for r in pooled if r["selected_for_main_result"] == "TRUE"]
prior_labels = {0.01: r"10^{-2}", 0.0001: r"10^{-4}", 0.000001: r"10^{-6}"}
a = prior_labels[float(selected["prior_per_cell"])]
mean = float(selected["posterior_mean"])
sd = float(selected["posterior_sd"])
raw = float(selected["empirical_proportion"])
numerator = int(selected["significant_inconclusive"])
denominator = int(selected["significant_analyses"])
output = [
    "% Generated by analysis/early_phase/render_inconclusive_results.py.",
    r"\textcolor{red}{The scatterplot is now also presented as a one-column Figure 3 in the manuscript, while remaining in Supplementary Figure S7B. Its inset uses the plotted two-sided $p$-value, including $p=2\min\{p_1,1-p_1\}$ for one-sided tests. "
    + rf"Among the {denominator:,} findings with plotted $p\le.05$, {numerator:,} ({100*raw:.2f}\%) have inconclusive Bayesian evidence, defined by $1/3\le\mathit{{eJAB}}\le3$. "
    + r"This denominator includes two opposite-tail one-sided findings beyond the 6,474 findings significant in their specified direction; neither additional finding is in the inconclusive band.}",
    "",
    r"\begingroup\color{red}",
    r"For each trial $j$, we cross-classify plotted $p\le.05$ with inconclusive evidence, giving counts $\boldsymbol{y}_j$ in the order (nonsignificant/conclusive, nonsignificant/inconclusive, significant/conclusive, significant/inconclusive). With $m_j$ eligible findings, the existing trial-level model gives",
    r"\[",
    r"\boldsymbol{\pi}_j\mid\boldsymbol{y}_j\sim\operatorname{Dirichlet}(y_{j1}+a,\ldots,y_{j4}+a),\qquad",
    r"\rho=\frac{\sum_j m_j\pi_{j4}}{\sum_j m_j(\pi_{j3}+\pi_{j4})}.",
    r"\]",
    r"All 1,790 trials are retained, with fixed eligible-finding-count weights. Thus $\rho$ is the proportion with inconclusive evidence among findings with plotted $p\le.05$, and its posterior uncertainty is conditional on the observed trials and weights. "
    + rf"With $a={a}$, the posterior mean is {mean:.5f} ({100*mean:.2f}\%) and posterior standard deviation is {sd:.5f} ({100*sd:.2f} percentage points). "
    + rf"This prior gives a mean within 0.01 percentage points of the raw proportion. The selected result uses {int(selected['draws']):,} independent posterior draws; the mean's Monte Carlo standard error is {100*float(selected['mcse_mean']):.4f} percentage points.",
    r"\endgroup",
    "",
    r"\begin{table}[!htbp]",
    r"\centering\begingroup\color{red}",
    r"\caption{Posterior proportion with inconclusive evidence among findings with plotted $p\le.05$, under the trial-level Dirichlet model. The raw proportion is " + f"{100*raw:.4f}" + r"\%.}\label{tab:inconclusive_posterior}",
    r"\begin{tabular}{rrr}",
    r"\toprule",
    r"$a$ & Posterior mean (\%) & Posterior SD (percentage points) \\",
    r"\midrule",
]
for row in pooled:
    output.append(rf"${prior_labels[float(row['prior_per_cell'])]}$ & {100*float(row['posterior_mean']):.3f} & {100*float(row['posterior_sd']):.3f} \\")
output += [r"\bottomrule", r"\end{tabular}", r"\endgroup", r"\end{table}"]
target = ROOT / "tmp/early_phase_latex/Inconclusive_results_response.tex"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("\n".join(output) + "\n")
print(target)
