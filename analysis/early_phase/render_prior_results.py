#!/usr/bin/env python3
"""Regenerate the SI input and a review copy for the consolidated response.

The response copy in tmp/early_phase_latex requires manual review and transfer;
the consolidated response document is not edited.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANUSCRIPT = ROOT / "Reassessing_the_Statistical_Evidence_in_Cancer_Research_Using_Approximate_Objective_Bayes_Factors"
REVIEW_DIR = ROOT / "tmp/early_phase_latex"
ROWS = list(csv.DictReader((ROOT / "analysis/early_phase/outputs/prior_sensitivity_summary.csv").open()))
PHASES = ["Early Phase I", "Phase I", "Phase II"]
PRIORS = [1e-2, 1e-4, 1e-6]
CAPTION = (r"Posterior sensitivity for the proportion of NHST-significant records with eJAB $>1$. "
           r"Each phase panel overlays kernel density estimates from 50,000 posterior draws under independent "
           r"per-trial Dirichlet$(a,a,a,a)$ priors, with eligible-analysis-count weights. "
           r"Grey dashed lines mark observed screening proportions; panel axes differ. "
           r"The eligible set, NHST rule, and eJAB threshold are held fixed across priors. "
           r"Small symmetric concentration parameters favor boundary configurations; the curves assess "
           r"sensitivity within this prior family.")


def render(path, response=False):
    fenv, tenv = "figure", "table"
    suffix = "response" if response else "supp"
    placement = "p" if response else "!htbp"
    height = ".72" if response else ".68"
    color = r"\color{red}" if response else ""
    text = ["% Generated by analysis/early_phase/render_prior_results.py.",
            rf"\begin{{{fenv}}}[{placement}]", r"\centering", r"\begingroup", color,
            rf"\includegraphics[width=.9\textwidth,height={height}\textheight,keepaspectratio]{{Prior_sensitivity.png}}",
            r"\caption{" + CAPTION + r"}\label{fig:prior_sensitivity_" + suffix + "}",
            r"\endgroup", rf"\end{{{fenv}}}",
            rf"\begin{{{tenv}}}[{placement}]", r"\centering\begingroup", color, r"\small",
            r"\caption{Posterior means and 95\% equal-tailed credible intervals for the fixed-cohort contradiction proportion. All entries are percentages. Each prior--phase combination uses 50,000 draws.}\label{tab:prior_results_" + suffix + "}",
            r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
            r"Phase & Observed & $a=10^{-2}$ & $a=10^{-4}$ & $a=10^{-6}$" + chr(92) * 2,
            r"\midrule"]
    for phase in PHASES:
        cells = [phase]
        group = [r for r in ROWS if r["phase"] == phase]
        assert len(group) == 3
        cells.append(f"{100 * float(group[0]['empirical_proportion']):.3f}")
        for prior in PRIORS:
            row = next(r for r in group if float(r["prior_per_cell"]) == prior)
            cells.append("{:.3f} [{:.3f}, {:.3f}]".format(*[100 * float(row[k]) for k in ("posterior_mean", "lower", "upper")]))
        text.append(" & ".join(cells) + chr(92) * 2)
    text += [r"\bottomrule", r"\end{tabular}", r"\par\vspace{4pt}",
             r"\begin{minipage}{.95\linewidth}\footnotesize Posterior mean Monte Carlo standard errors are at most 0.0074 percentage points; batch-based interval-endpoint Monte Carlo standard errors are at most 0.0274 percentage points. For $10^{-4}$ versus $10^{-6}$, posterior mean changes are below 0.004 percentage points in every phase. The $10^{-2}$ means exceed the $10^{-6}$ means by 0.369, 0.261, and 0.211 percentage points, respectively.\end{minipage}",
             r"\endgroup", rf"\end{{{tenv}}}"]
    path.write_text("\n".join(text) + "\n")


if __name__ == "__main__":
    REVIEW_DIR.mkdir(parents=True, exist_ok=True)
    render(MANUSCRIPT / "SI/Prior_sensitivity_results.tex")
    render(REVIEW_DIR / "Prior_sensitivity_results_response.tex", response=True)
    print(f"Regenerated SI input: {MANUSCRIPT / 'SI/Prior_sensitivity_results.tex'}")
    print(f"Response review copy: {REVIEW_DIR / 'Prior_sensitivity_results_response.tex'}; transfer reviewed changes into the consolidated response manually.")
